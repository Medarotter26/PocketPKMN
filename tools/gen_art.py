#!/usr/bin/env python3
"""gen_art.py - turns art/ into C.

  art/font.txt      -> source/pw_font.c
  art/icons/*.txt   -> source/pw_menu_art.c + include/pw_menu_art.h
  (+ text slots rendered with the font, see tools/pwimg.py SLOTS)

Run from anywhere:  python3 tools/gen_art.py
Fails (exit 1) if an icon has the wrong size, a slot overlaps, or a text
does not fit its slot.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pwimg  # noqa: E402

ROOT = pwimg.ROOT


def c_bytes(data, indent="    ", per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(indent + ", ".join("0x%02X" % b for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def gen_font():
    font = pwimg.load_font()
    out = []
    out.append("// pw_font.c - GENERATED by tools/gen_art.py from art/font.txt. Do not edit.")
    out.append("// WalkerBox original proportional pixel font: cap height 9, x-height 6,")
    out.append("// descender 3, 2 accent rows above the caps; line height 16.")
    out.append("// rows[0..13]: bit 7 = leftmost pixel. Advance = w + 1.")
    out.append('#include "pw_image.h"')
    out.append("")
    out.append("const pw_glyph_t pw_font_glyphs[PW_FONT_COUNT] = {")
    for i, (w, rows) in enumerate(font):
        if i < 95:
            ch = chr(0x20 + i)
            label = "space" if ch == " " else ch
        else:
            label = "e-acute" if i == 95 else "E-acute"
        vals = []
        for r in rows:
            v = 0
            for c, p in enumerate(r):
                if p == "#":
                    v |= 0x80 >> c
            vals.append("0x%02X" % v)
        if label in ("\\",):
            label = "backslash"
        out.append("    {%d, {%s}}, // %s" % (w, ", ".join(vals), label))
    out.append("};")
    out.append("")
    with open(os.path.join(ROOT, "source", "pw_font.c"), "w", newline="\n") as f:
        f.write("\n".join(out))


def gen_menu_art():
    pwimg.check_slots()
    problems = []
    arrays = []
    table = []
    names = []
    n_text = n_icon = n_blank = n_other = 0
    for sl in pwimg.SLOTS:
        sh, data, fit = pwimg.render_slot(sl)
        if not fit:
            problems.append("%s (0x%04X): text does not fit %dx%d" %
                            (sl["name"], sl["addr"], sl["w"], sl["h"]))
        k = sl["kind"]
        if k in ("text", "heading", "frame", "digit"):
            n_text += 1
        elif k == "icon":
            n_icon += 1
        elif k == "blank":
            n_blank += 1
        else:
            n_other += 1
        what = sl["arg"] if k in ("text", "heading", "frame", "digit") else sl["arg"] or ""
        what = (what or "").replace("\n", "\\n").replace("\u00e9", "e'").replace("\u00c9", "E'")
        comment = "%s %s %s" % (k, sl["name"], ('"%s"' % what) if k in ("text", "heading", "frame", "digit") else "")
        if data is None:
            table.append("    {0x%04X, %d, %d, NULL}, // %s" % (sl["addr"], sl["w"], sl["h"], comment.strip()))
        else:
            assert len(data) == pwimg.slot_size(sl)
            arr = "art_" + sl["name"]
            arrays.append("// 0x%04X %dx%d %s\nstatic const uint8_t %s[%d] = {\n%s\n};\n" %
                          (sl["addr"], sl["w"], sl["h"], comment.strip(), arr, len(data), c_bytes(data)))
            table.append("    {0x%04X, %d, %d, %s}, // %s" % (sl["addr"], sl["w"], sl["h"], arr, comment.strip()))
        names.append('    "%s",' % sl["name"])
    if problems:
        for p in problems:
            print("ERROR:", p)
        sys.exit(1)

    c = []
    c.append("// pw_menu_art.c - GENERATED by tools/gen_art.py from art/. Do not edit.")
    c.append("// WalkerBox original menu art for a blank Pokewalker, EEPROM 0x0280-0x8C6F.")
    c.append("// Slot addresses/sizes follow Dmitry Grinberg's EEPROM map.")
    c.append("// Slot 0x0648 is a raw 8-byte AND mask (listed as 4x8 so w*(h/8)*2 == 8).")
    c.append('#include "pw_menu_art.h"')
    c.append("")
    c.append("#include <stddef.h>")
    c.append("#include <string.h>")
    c.append("")
    c.extend(arrays)
    c.append("const pw_menu_slot_t pw_menu_slots[PW_MENU_SLOT_COUNT] = {")
    c.extend(table)
    c.append("};")
    c.append("")
    c.append("const char *const pw_menu_slot_names[PW_MENU_SLOT_COUNT] = {")
    c.extend(names)
    c.append("};")
    c.append("")
    c.append("size_t pw_menu_slot_size(const pw_menu_slot_t *s)")
    c.append("{")
    c.append("    return (size_t)s->w * (size_t)(s->h / 8) * 2u;")
    c.append("}")
    c.append("")
    c.append("void pw_menu_art_fill(uint8_t *eeprom64k)")
    c.append("{")
    c.append("    // white everywhere in the art range first (unused/unknown gaps)")
    c.append("    memset(eeprom64k + PW_MENU_ART_START, 0, PW_MENU_ART_END - PW_MENU_ART_START);")
    c.append("    for (int i = 0; i < PW_MENU_SLOT_COUNT; i++) {")
    c.append("        const pw_menu_slot_t *s = &pw_menu_slots[i];")
    c.append("        size_t n = pw_menu_slot_size(s);")
    c.append("        if (s->addr < PW_MENU_ART_START || s->addr + n > PW_MENU_ART_END)")
    c.append("            continue; // never write outside 0x0280-0x8C6F")
    c.append("        if (s->data)")
    c.append("            memcpy(eeprom64k + s->addr, s->data, n);")
    c.append("    }")
    c.append("}")
    c.append("")
    with open(os.path.join(ROOT, "source", "pw_menu_art.c"), "w", newline="\n") as f:
        f.write("\n".join(c))

    h = []
    h.append("// pw_menu_art.h - GENERATED by tools/gen_art.py. Do not edit.")
    h.append("// WalkerBox original menu art set for EEPROM 0x0280-0x8C6F of a blank walker.")
    h.append("#ifndef PW_MENU_ART_H")
    h.append("#define PW_MENU_ART_H")
    h.append("")
    h.append("#include <stddef.h>")
    h.append("#include <stdint.h>")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append('extern "C" {')
    h.append("#endif")
    h.append("")
    h.append("#define PW_MENU_ART_START 0x0280u  // first byte written")
    h.append("#define PW_MENU_ART_END   0x8C70u  // one past the last byte (0x8C6F)")
    h.append("#define PW_MENU_SLOT_COUNT %d" % len(pwimg.SLOTS))
    h.append("")
    h.append("// One image slot. data == NULL means the slot is left white (unused,")
    h.append("// or filled at run time like the trainer name at 0x1250).")
    h.append("// Size in bytes = w * (h/8) * 2 (see pw_menu_slot_size).")
    h.append("typedef struct {")
    h.append("    uint16_t addr;")
    h.append("    uint8_t w, h;")
    h.append("    const uint8_t *data;")
    h.append("} pw_menu_slot_t;")
    h.append("")
    h.append("extern const pw_menu_slot_t pw_menu_slots[PW_MENU_SLOT_COUNT];")
    h.append("extern const char *const pw_menu_slot_names[PW_MENU_SLOT_COUNT];")
    h.append("")
    h.append("size_t pw_menu_slot_size(const pw_menu_slot_t *s);")
    h.append("")
    h.append("// Writes every slot into a 64 KiB EEPROM image at its address; gaps in")
    h.append("// 0x0280-0x8C6F become white (0). Touches nothing outside 0x0280-0x8C6F")
    h.append("// (in particular not 0x8C70-0x8EFF).")
    h.append("void pw_menu_art_fill(uint8_t *eeprom64k);")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif")
    h.append("")
    with open(os.path.join(ROOT, "include", "pw_menu_art.h"), "w", newline="\n") as f:
        f.write("\n".join(h))

    print("slots: %d total = %d font-rendered (text/heading/frame/digit), %d drawn icons, "
          "%d other (mask/placard), %d white" % (len(pwimg.SLOTS), n_text, n_icon, n_other, n_blank))


if __name__ == "__main__":
    gen_font()
    gen_menu_art()
    print("wrote source/pw_font.c, source/pw_menu_art.c, include/pw_menu_art.h")
