#!/usr/bin/env python3
"""Builds the Pokemon Diamond / Pearl / Platinum route file from the user's DPPt course workbook.

usage: python3 -I tools/routes_dppt.py [workbook] [out]
  workbook  default: $POCKETPKMN_COURSES/DPt Pokewalker Courses.xlsx (env), else ../walker courses/... (read only)
  out       default: romfs/routes/dppt.txt

Same file format as tools/routes_xy.py / routes_sm.py (shared helpers from routes_xy). Pokemon lines carry
origin=D,P,Pt (the sheet's "Origin game to set") and ha=0 (Gen 4 has no hidden abilities). Unlocks: badges=N, hof,
hof watts=N. Moves: the last 4 level-up moves at that level in Platinum (PokeAPI data in art_src/pokeapi; the
templates check them in Diamond / Pearl too).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import routes_xy as rx  # noqa: E402
import routes_sm as rs  # noqa: E402  (load_learnsets)

DEFAULT_BOOK = os.path.join(os.environ.get("POCKETPKMN_COURSES", os.path.join(os.path.dirname(ROOT), "walker courses")),
                            "DPt Pokewalker Courses.xlsx")
DEFAULT_OUT = os.path.join(ROOT, "romfs", "routes", "dppt.txt")

# The user's decisions -------------------------------------------------------
# names wider than the walker's 80 px: Champion's Bazaar (81) and Abandoned Factory (84) as in X/Y; Seaside Lighthouse
# (84) -> Lighthouse Coast (76, chosen 2026-11-15, the closest meaning)
COURSE_RENAMES = {"Champion's Bazaar": "Elite Bazaar", "Abandoned Factory": "Rusted Works",
                  "Seaside Lighthouse": "Lighthouse Coast"}
ORIGINS = [  # sheet text (start) -> games
    ("Walker's own game", "D,P,Pt"), ("Diamond or Platinum", "D,Pt"), ("Pearl or Platinum", "P,Pt"),
    ("Diamond", "D"), ("Pearl", "P"), ("Platinum", "Pt"),
]
# Course pictures (romfs/routes/pictures/<name>.txt, tools/route_art.py). Names shared with other games share their
# picture; DPPT1 in route_art.py draws the rest.
PICTURES = {
    "Lakefront": "lakefront", "Rusted Works": "rusted_works", "Deep Woods": "deep_woods",
    "Blossom Garden": "blossom_garden", "Shopping Center": "shopping_district", "Residential Zone": "suburban_area",
    "Night Meadow": "night_meadow", "Crumbling Crag": "crumbling_crag", "Rugged Hills": "rugged_hills",
    "Marsh Wetlands": "marsh_wetlands", "Iron Mine": "iron_mine", "Frozen Peak": "snowy_summit",
    "Lighthouse Coast": "lighthouse_coast", "Starter's Lane": "starters_lane", "Wild Safari": "wild_safari",
    "Trader's Crossing": "traders_crossing", "Elite Bazaar": "elite_bazaar",
}
ITEM_CHOICES = {"Power Bracer (or another Power item)": "Power Bracer"}  # as in the other games
GEN4_MAX_ITEM = 467  # last Platinum item id
MAX_SPECIES = 493


def parse_origin(text):
    t = str(text).strip()
    for start, games in ORIGINS:
        if t.startswith(start):
            return games
    raise SystemExit("unknown origin game: %r" % t)


def main():
    book = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_BOOK
    out_path = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    import openpyxl
    wb = openpyxl.load_workbook(book, read_only=True, data_only=True)

    species, moves, items = rx.NameList("species"), rx.NameList("moves"), rx.NameList("items")
    learnsets = rs.load_learnsets("platinum")

    courses, by_name = [], {}
    for r in wb["Courses"].iter_rows(min_row=2, values_only=True):
        if not r or r[0] is None:
            continue
        cname = COURSE_RENAMES.get(r[0], r[0])
        if cname not in by_name:
            fav = ",".join(t.strip() for t in str(r[9]).split("/"))
            by_name[cname] = [cname, rx.parse_unlock(r[1]), fav, [], []]
            courses.append(by_name[cname])
        by_name[cname][3].append((str(r[3]).strip(), str(r[4]).strip(), int(r[5]), int(r[6]), parse_origin(r[10])))

    irows = list(wb["Items"].iter_rows(values_only=True))
    hdr = next(i for i, r in enumerate(irows) if r and r[0] == "Course")
    for r in irows[hdr + 1:]:
        if not r or r[0] is None:
            continue
        cname = COURSE_RENAMES.get(r[0], r[0])
        if cname not in by_name:
            raise SystemExit("Items sheet course not in Courses sheet: %r" % r[0])
        by_name[cname][4].append((int(r[2]), str(r[3]).strip()))

    unresolved, problems = [], []
    lines = [
        "; PocketPKMN routes for Pokemon Diamond / Pearl / Platinum - generated by tools/routes_dppt.py "
        "from the user's workbook (do not edit by hand)",
        "game d p pt",
    ]
    for n, (cname, unlock, fav, pokes, its) in enumerate(courses):
        if rx.name_width(cname) > rx.WIDTH_LIMIT["course"]:
            problems.append("course name too wide: %s (%d px)" % (cname, rx.name_width(cname)))
        if cname not in PICTURES:
            raise SystemExit("no picture for course %r" % cname)
        lines.append("")
        lines.append("course %d | %s | unlock=%s | picture=%s | favoured=%s" % (n, cname, unlock, PICTURES[cname], fav))
        for grp in ("A", "B", "C"):
            members = [p for p in pokes if p[0] == grp]
            if len(members) != 2:
                raise SystemExit("%s group %s has %d Pokemon" % (cname, grp, len(members)))
            slot, chance = rx.GROUP_SLOT[grp]
            for _, pname, level, steps, origin in members:
                if grp == "A":
                    steps = 0  # the walker shows group A anyway (user 2026-11-15)
                sid = species.find(pname)
                if sid is None or sid > MAX_SPECIES:
                    unresolved.append("species: " + pname)
                    continue
                sname = species.names[sid]
                if rx.name_width(sname) > rx.WIDTH_LIMIT["poke"]:
                    problems.append("Pokemon name too wide: %s" % sname)
                mv = rx.wild_moves(learnsets.get(sid, []), level)
                if mv.count(0):
                    problems.append("%s Lv%d has only %d level-up moves (%s)" % (sname, level, 4 - mv.count(0), cname))
                mnames = ", ".join(moves.names[m] for m in mv if m)
                lines.append("poke %s %d %d %d %d %d %d %d %d %d form=0 origin=%s ha=0 ; %s: %s"
                             % (grp, slot, chance, sid, level, steps, *mv, origin, sname, mnames))
        if len(its) != 10:
            raise SystemExit("%s has %d items" % (cname, len(its)))
        ordered = sorted(enumerate(its), key=lambda e: (-e[1][0], e[0]))
        for rank, (_, (steps, iname)) in enumerate(ordered):
            iname = ITEM_CHOICES.get(iname, iname)
            iid = items.find(iname)
            if iid is None or iid > GEN4_MAX_ITEM:
                unresolved.append("item: " + iname)
                continue
            if rx.name_width(items.names[iid]) > rx.WIDTH_LIMIT["item"]:
                problems.append("item name too wide: %s (%d px)" % (items.names[iid], rx.name_width(items.names[iid])))
            lines.append("item %d %d %d %d all ; %s" % (rank, rx.ITEM_CHANCES[rank], iid, steps, items.names[iid]))

    if unresolved:
        print("UNRESOLVED NAMES (nothing written):")
        for u in sorted(set(unresolved)):
            print("  " + u)
        sys.exit(1)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d courses" % (out_path, len(courses)))
    for p in problems:
        print("note: " + p)


if __name__ == "__main__":
    main()
